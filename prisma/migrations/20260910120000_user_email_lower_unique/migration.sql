-- ОДИН ЧЕЛОВЕК — ОДНА УЧЁТНАЯ ЗАПИСЬ, НЕЗАВИСИМО ОТ РЕГИСТРА.
--
-- Сравнение уже нечувствительно к регистру (src/lib/auth/email-identity.ts),
-- и этого достаточно, чтобы ЗАВЕСТИ второго пользователя не получилось: все
-- три пути поиска человека по почте идут через одно условие.
--
-- Но код — не последняя линия. Импорт, ручная правка в psql, будущий путь
-- регистрации, о котором сегодня никто не думает, — любой из них может
-- положить в базу `Ivan@ya.ru` рядом с `ivan@ya.ru`. База должна отказать
-- сама, а не полагаться на то, что все помнят про сравнение.
--
-- ПОЧЕМУ ЭТО МОЖНО СТАВИТЬ ИМЕННО СЕЙЧАС. Индекс на грязных данных уронил бы
-- выкладку, поэтому раньше он не ставился вслепую. Диагностика боевой базы
-- (прогон 58, 10.09.2026) ответила числами:
--
--   адресов, отзывающихся более чем на одну учётную запись: 0
--   адресов, записанных не в нижнем регистре:               0
--
-- Двойников нет, и создание индекса ничего не найдёт нарушенным.
--
-- Функциональный индекс в схеме Prisma не выражается — он живёт только здесь.
-- Рядом с User.email в prisma/schema.prisma стоит ссылка на эту миграцию,
-- чтобы `prisma migrate dev` его не снёс как незнакомый.
CREATE UNIQUE INDEX IF NOT EXISTS "User_email_lower_key" ON "User" (lower(email));
