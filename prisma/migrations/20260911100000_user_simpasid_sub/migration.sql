-- Постоянный идентификатор человека в СИМПАС.
--
-- По почте человек ищется только при первом связывании: смена почты в
-- аккаунте СИМПАС — штатное действие, и поиск по ней после смены завёл бы
-- вторую пустую практику рядом с настоящей.
--
-- Добавление колонки и уникального индекса. Существующие строки не
-- трогаются: у всех, кто вошёл прежними способами, здесь NULL, а @unique в
-- PostgreSQL множеству NULL не мешает.
ALTER TABLE "User" ADD COLUMN "simpasIdSub" TEXT;
CREATE UNIQUE INDEX "User_simpasIdSub_key" ON "User"("simpasIdSub");
