-- O-260829: «Подбор времени» (time-picker вместо календарной сетки) был
-- написан ещё в v1, но оставался недостижим для всех: PsychologistSettings.
-- timeSuggestEnabled стоял в false по умолчанию, и ни одного места, где
-- специалист мог бы его включить, в продукте не существовало — флаг читается
-- в src/app/bot/actions.ts и src/app/bot/book/BookingPageClient.tsx и больше
-- нигде. Клиенты при этом видели старую календарную сетку вместо экрана
-- подбора времени из прототипа v2 (docs/design/booking_prototype_v2.html,
-- экран 1), хотя ТЗ v2 §3 числит эту механику среди «уже сделанного верно».
--
-- Смена @default в схеме действует только на строки, создаваемые после неё,
-- поэтому уже заведённым настройкам флаг проставляется здесь. Обновляем
-- только те строки, где он ещё false: если кто-то осознанно выключит подбор
-- позже, повторный прогон миграции (её не будет, но всё же) не переспорит
-- это решение.
UPDATE "PsychologistSettings" SET "timeSuggestEnabled" = true WHERE "timeSuggestEnabled" = false;
