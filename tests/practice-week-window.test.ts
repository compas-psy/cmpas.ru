// Календарная неделя специалиста: понедельник–воскресенье.
//
// До этого «неделя» в системе понималась двумя способами одновременно:
// календарь в приложении считал её Пн–Вс, а плитка «за неделю» на дашборде
// — как последние семь дней НАЗАД. Разница не теоретическая: специалист в
// понедельник смотрел на встречу в среду, а в старое окно (пред. пн –
// сегодня) она не попадала ПО ПОСТРОЕНИЮ. Плитка молчала ровно о том, к
// чему он готовится.
//
// Здесь проверяются границы — самое скучное и самое ломкое место.

import { describe, it, expect } from 'vitest';
import { isoWeekWindow, startOfIsoWeek, utcDayStart, addDays } from '../src/lib/practice/week-window';

const utc = (iso: string) => new Date(`${iso}T00:00:00.000Z`);
const day = (d: Date) => d.toISOString().slice(0, 10);

describe('календарная неделя', () => {
    it('понедельник — начало своей же недели', () => {
        expect(day(startOfIsoWeek(utc('2026-09-07')))).toBe('2026-09-07');
    });

    // Тот самый случай: смотрим в понедельник, встреча в среду.
    it('среда попадает в ту же неделю, что и понедельник', () => {
        const { start, end } = isoWeekWindow(utc('2026-09-07'));
        const wednesday = utc('2026-09-09');
        expect(wednesday >= start && wednesday < end).toBe(true);
    });

    // getUTCDay() отдаёт воскресенье нулём. Без приведения 0 → 7
    // воскресенье уехало бы в начало СЛЕДУЮЩЕЙ недели — то есть счётчик
    // обнулялся бы в последний день недели, когда он нужнее всего.
    it('воскресенье принадлежит уходящей неделе, а не следующей', () => {
        expect(day(startOfIsoWeek(utc('2026-09-13')))).toBe('2026-09-07');
        const { start, end } = isoWeekWindow(utc('2026-09-13'));
        expect(day(start)).toBe('2026-09-07');
        expect(day(end)).toBe('2026-09-14');
    });

    it('следующий понедельник в окно уже не входит', () => {
        const { end } = isoWeekWindow(utc('2026-09-07'));
        expect(utc('2026-09-14') >= end).toBe(true);
    });

    it('прошлая среда в текущую неделю не входит', () => {
        const { start } = isoWeekWindow(utc('2026-09-07'));
        expect(utc('2026-09-02') < start).toBe(true);
    });

    it('окно ровно семь дней', () => {
        const { start, end } = isoWeekWindow(utc('2026-09-10'));
        expect((end.getTime() - start.getTime()) / (24 * 3600 * 1000)).toBe(7);
    });

    it('неделя через границу месяца считается так же', () => {
        expect(day(startOfIsoWeek(utc('2026-09-01')))).toBe('2026-08-31');
    });

    // Границы берутся в UTC, а не через setHours: даты сессий записаны как
    // полночь UTC, и смешение с часовым поясом ОС сервера сдвинуло бы
    // «сегодня» на сутки при переезде контейнера.
    it('время суток на границы не влияет', () => {
        const lateEvening = new Date('2026-09-07T23:59:59.000Z');
        expect(day(utcDayStart(lateEvening))).toBe('2026-09-07');
        expect(day(startOfIsoWeek(lateEvening))).toBe('2026-09-07');
    });

    it('сдвиг на дни не зависит от перехода через месяц', () => {
        expect(day(addDays(utc('2026-08-31'), 1))).toBe('2026-09-01');
    });
});
