// Задача 27: к человеку обращаются по имени, а не по фамилии.
//
// На дашборде было одно правило на два источника с противоположным порядком
// слов, и специалиста, вошедшего через Яндекс, встречали фамилией. Здесь
// зафиксировано, какое слово берётся откуда — чтобы правило нельзя было
// снова свести к одному «последнему токену».

import { describe, it, expect } from 'vitest';
import { greetingName } from '@/app/diary/page';

describe('имя для приветствия', () => {
    it('профиль подписан «Фамилия и Имя» — берётся последнее слово', () => {
        expect(greetingName('Соколова-Преображенская Мария', null)).toBe('Мария');
        expect(greetingName('Иванова Анна', null)).toBe('Анна');
    });

    it('вход через провайдера отдаёт «Имя Фамилия» — берётся первое слово', () => {
        expect(greetingName(null, 'Мария Соколова-Преображенская')).toBe('Мария');
        expect(greetingName('', 'Анна Иванова')).toBe('Анна');
    });

    it('профиль важнее: его человек заполнял сам', () => {
        expect(greetingName('Соколова Мария', 'Maria Sokolova')).toBe('Мария');
    });

    it('одно слово остаётся собой в любом источнике', () => {
        expect(greetingName('Мария', null)).toBe('Мария');
        expect(greetingName(null, 'Мария')).toBe('Мария');
    });

    it('пустое имя не превращается в приветствие с запятой', () => {
        expect(greetingName(null, null)).toBe('');
        expect(greetingName('   ', '  ')).toBe('');
    });
});
