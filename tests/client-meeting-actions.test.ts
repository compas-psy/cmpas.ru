// «Мои встречи» — единственная страница, где встреча показана как встреча.
//
// До 10.09.2026 она умела только отменить. «Перенести» уводило на страницу
// НОВОЙ записи, а подтвердить встречу клиент не мог нигде, кроме кнопки в
// напоминании за сутки — то есть до напоминания ничем.
//
// Учредитель на живом проходе: «переходя по которой вижу страницу, где нет
// нихрена никаких подтверждений, а просто страница записи» — и отдельно:
// по прошедшей встрече уместны и «просто забронировать слот», и
// «забронировать слот через неделю».

import { describe, it, expect } from 'vitest';
import { readFileSync } from 'fs';

const PAGE = 'src/app/bot/client/page.tsx';
const API = 'src/app/api/user/diary/bot/client/sessions/route.ts';

/**
 * Текст без комментариев: объяснение «здесь намеренно нет X» — не показ X.
 *
 * Блочные комментарии вырезаются целиком, а не построчно: в JSX они пишутся
 * без звёздочек в начале строк, и построчный фильтр их не ловит.
 */
function code(path: string): string {
    return readFileSync(path, 'utf8')
        .replace(/\/\*[\s\S]*?\*\//g, '')
        .split('\n')
        .filter(line => !line.trimStart().startsWith('//'))
        .join('\n');
}

describe('предстоящая встреча', () => {
    it('подтвердить можно здесь, а не только из напоминания', () => {
        expect(code(PAGE)).toContain('Подтверждаю');
    });

    it('перенос ведёт на страницу переноса, а не на новую запись', () => {
        const body = code(PAGE);
        expect(body).toContain('selectedSession.reschedule');
    });

    it('сервер раздаёт поимённые адреса всех трёх действий', () => {
        expect(code(API)).toContain('sessionActionLinks');
    });
});

describe('прошедшая встреча', () => {
    it('два пути записи: тот же час через неделю и другое время', () => {
        const body = code(PAGE);
        expect(body).toContain('Тот же час через неделю');
        expect(body).toContain('Выбрать другое время');
    });

    it('«тот же час» открывает страницу записи на нужный день и час', () => {
        // Час НЕ бронируется по ссылке: в адресе только пожелание, какой день
        // и время открыть. Настоящая бронь по-прежнему проходит через
        // подписанный слот и проверку занятости.
        expect(code(PAGE)).toMatch(/\?date=\$\{dateStr\}&time=/);
    });

    it('«регулярно на срок» клиенту не предлагается', () => {
        // Занимая чужие среды на три месяца вперёд, клиент распоряжается
        // расписанием специалиста — такое решение принимает специалист.
        // Решение учредителя от 10.09.2026 по развилке 1.
        const body = code(PAGE);
        expect(body).not.toContain('на срок');
        expect(body).not.toContain('12 недель');
    });
});

describe('ссылка из сообщения открывает саму встречу', () => {
    it('страница читает номер встречи из адреса', () => {
        expect(code(PAGE)).toContain("searchParams.get('s')");
    });
});
