import { describe, it, expect } from 'vitest';
import { documentDisplayTitle } from '@/lib/documents/display-title';

/**
 * Клиент открыл ссылку на информированное согласие и увидел заголовок,
 * обрезанный по краю экрана: «Информированное_согласие_оф … Мартынов».
 *
 * Причина не в стилях. Название документа — это имя загруженного файла, а
 * подчёркивание для браузера переносом не является: вся строка — одно слово.
 */
describe('название документа для человека', () => {
    it('имя файла из настоящего случая читается как название', () => {
        expect(documentDisplayTitle('Информированное_согласие_оферта___Илья_Мартынов.pdf'))
            .toBe('Информированное согласие оферта Илья Мартынов');
    });

    it('расширение уходит из названия — файл остаётся файлом', () => {
        expect(documentDisplayTitle('Договор.docx')).toBe('Договор');
        expect(documentDisplayTitle('скан.JPEG')).toBe('скан');
    });

    it('нормальное название не трогается', () => {
        // Правка не имеет права переписывать то, что специалист назвал сам.
        expect(documentDisplayTitle('Информированное согласие')).toBe('Информированное согласие');
        expect(documentDisplayTitle('Согласие 152-ФЗ, редакция 2026')).toBe('Согласие 152-ФЗ, редакция 2026');
    });

    it('точка внутри названия не считается расширением', () => {
        expect(documentDisplayTitle('Согласие. Версия для взрослых')).toBe('Согласие. Версия для взрослых');
    });

    it('пустое название заменяется именем файла', () => {
        expect(documentDisplayTitle('', 'соглашение_2026.pdf')).toBe('соглашение 2026');
        expect(documentDisplayTitle(null, null)).toBe('Документ');
    });

    it('название из одних подчёркиваний не превращается в пустоту', () => {
        // Пустой заголовок хуже некрасивого: человек не поймёт, что открыл.
        expect(documentDisplayTitle('___')).toBe('___');
    });
});
