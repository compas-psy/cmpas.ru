#!/usr/bin/env bash
# Задача 28, §20: финальная проверка журналов на утечку личного.
#
# На вход — файл журнала приложения, снятый во время приёмочных прогонов.
# Ищутся не «слова вообще», а ровно то, чего в журнале быть не должно:
# имена и телефоны синтетических клиентов, тексты сообщений, названия
# событий календаря, поисковые строки адреса и любые токены.
#
# Что журналу МОЖНО: correlation_id, машинный error_code, имя провайдера,
# источник и числа. Их наличие проверяется отдельно — журнал без единого
# опознавательного знака так же плох, как журнал с фамилией: по нему нельзя
# разобрать инцидент.
set -uo pipefail

LOG="${1:-/tmp/stand.log}"
if [ ! -f "$LOG" ]; then
    echo "журнала нет: $LOG"
    exit 0
fi

LINES=$(wc -l < "$LOG")
echo "===== ПРОВЕРКА ЖУРНАЛА НА ЛИЧНОЕ ====="
echo "файл: $LOG, строк: $LINES"

LEAKS=0

# Каждая пара — что ищем и как это назвать в отчёте. Значения взяты из
# синтетического посева: настоящих людей в прогоне нет, но если бы утечка
# была, она выглядела бы ровно так же.
check() {
    local pattern="$1" label="$2"
    local n
    n=$(grep -c -E "$pattern" "$LOG" 2>/dev/null || true)
    n=${n:-0}
    if [ "$n" -gt 0 ]; then
        echo "УТЕЧКА: $label — $n строк"
        grep -n -E "$pattern" "$LOG" | head -3 | cut -c1-160
        LEAKS=$((LEAKS + 1))
    else
        echo "чисто: $label"
    fi
}

check 'Ковалевская|Соколова-Преображенская|Анастасия Владимировна' 'ФИО клиента или специалиста'
check '\+7[0-9]{10}|\+7 ?\(?[0-9]{3}\)?[ -]?[0-9]{3}' 'телефон'
check '[A-Za-z0-9._%+-]+@(task27|task28)\.invalid' 'адрес почты'
check 'structuredNotes|privateNotes|clientSummary' 'имена полей заметок рядом со значением'
check 'sat1_[A-Za-z0-9]|st1_[A-Za-z0-9]' 'подписанный токен ссылки'
check 'accessToken=|refreshToken=|Bearer [A-Za-z0-9._-]{20}' 'токен доступа'
check 'initData|tgWebAppData|hash=[a-f0-9]{64}' 'сырые данные Telegram'
check 'Яузская|Каменноостровский|Баумана' 'строка адреса кабинета'
check 'X-Max-Bot-Api-Secret: [A-Za-z0-9]' 'секрет приёмника MAX'

echo
echo "===== ЧТО В ЖУРНАЛЕ ЕСТЬ ПОЛЕЗНОГО ====="
for token in correlation_id error_code source provider; do
    n=$(grep -c -- "$token" "$LOG" 2>/dev/null || true)
    echo "$token: ${n:-0} строк"
done

echo
if [ "$LEAKS" -eq 0 ]; then
    echo "ИТОГ: утечек не найдено (0 из 9 проверок сработало)"
    exit 0
fi
echo "ИТОГ: сработало проверок — $LEAKS"
exit 1
