#!/usr/bin/env bash
# Сторож конфигурации выкладки (Задача 19).
#
# Интеграция, у которой не настроен ключ, ломается тихо: подсказки адресов
# просто перестают появляться, и понять, что виноват отсутствующий
# DADATA_API_KEY, а не «редкий адрес», по экрану невозможно. Приложение теперь
# честно отвечает 503 NOT_CONFIGURED, но узнавать об этом от специалиста —
# поздно. Поэтому отсутствие ключа называется ЗДЕСЬ, до выкладки.
#
# Секрет в репозиторий не кладётся и запасного ключа не заводится: сторож
# только проверяет, что значение пришло из окружения выкладки.
#
# Использование:
#   check-deploy-config.sh            # диагностирует, код возврата 0
#   check-deploy-config.sh --strict   # то же, но ненастроенное роняет прогон
#
# Значения не печатаются никогда — только имена ключей и факт наличия.

set -uo pipefail

STRICT=0
[ "${1:-}" = "--strict" ] && STRICT=1

# Ключи, без которых продукт работает, но с явно потерянной возможностью.
# Формат: ИМЯ|что именно перестаёт работать
OPTIONAL_KEYS=(
    "DADATA_API_KEY|подсказки адресов кабинета ответят 503 NOT_CONFIGURED — адрес придётся вводить полностью вручную"
)

missing=0

echo "Проверка конфигурации выкладки:"

for entry in "${OPTIONAL_KEYS[@]}"; do
    key="${entry%%|*}"
    consequence="${entry#*|}"
    value="${!key:-}"
    if [ -n "$value" ]; then
        echo "  ✓ $key настроен"
    else
        missing=$((missing + 1))
        echo "  ✗ $key НЕ НАСТРОЕН: $consequence" >&2
    fi
done

if [ "$missing" -gt 0 ]; then
    echo "" >&2
    echo "Не настроено ключей: $missing. Добавьте их в секреты окружения выкладки" >&2
    echo "(GitHub → Settings → Secrets). Значение в репозиторий не коммитить." >&2
    [ "$STRICT" -eq 1 ] && exit 1
    exit 0
fi

echo "Вся проверяемая конфигурация на месте."
exit 0
