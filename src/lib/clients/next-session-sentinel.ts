/**
 * «31 ДЕКАБРЯ» В КАРТОЧКЕ КЛИЕНТА, У КОТОРОГО НЕТ НИ ОДНОЙ ВСТРЕЧИ.
 *
 * У только что заведённого клиента nextSessionDate ставится в 9999-12-31 —
 * не как дата, а как признак «этот клиент только что создан, не уводи с него
 * выбор»: список сам выбирает карточку с ближайшей встречей, и без этой
 * метки специалист, заведя человека, тут же терял его из виду.
 *
 * Приём рабочий, но метка утекла на экран: в списке у новых клиентов
 * печаталось «31 дек.» — дата, которой не существует ни в чьём расписании.
 * Технический признак нельзя показывать как факт о человеке, поэтому здесь
 * он назван один раз, и здесь же — правило, как его узнать при показе.
 *
 * Порог намеренно грубый: год 9000. Настоящая запись так далеко не заходит
 * (повтор ограничен полугодом), а сравнение с точной датой сломалось бы от
 * любой правки часового пояса.
 */

export const NEW_CLIENT_SORT_SENTINEL = new Date('9999-12-31T00:00:00.000Z');

/** true — это техническая метка сортировки, а не дата встречи. */
export function isSortSentinelDate(value: Date | string | null | undefined): boolean {
    if (!value) return false;
    const date = value instanceof Date ? value : new Date(value);
    return !Number.isNaN(date.getTime()) && date.getUTCFullYear() >= 9000;
}
