/**
 * СКЛОНЕНИЕ СЛОВА ПРИ ЧИСЛЕ — ОДНО ПРАВИЛО НА ПРОДУКТ.
 *
 * Правило жило в четырёх местах в двух разных редакциях, и две из них были
 * неверны. Короткая версия — `n === 1 ? 'день' : n < 5 ? 'дня' : 'дней'` —
 * права до десяти и ошибается дальше: она даёт «21 дней» и «22 дней» вместо
 * «21 день» и «22 дня». Ровно в этом промежутке и живёт пробный период.
 *
 * Мелочь, которую видно каждому: человек читает «осталось 22 дней» и по одной
 * этой строке решает, насколько аккуратно сделано остальное.
 */

/**
 * Русское склонение по числу.
 *
 * Порядок форм тот же, что принят в переводах: одна, две-четыре, много.
 * Исключение для 11–14 стоит первым: у них последняя цифра обманывает.
 */
export function plural(count: number, one: string, few: string, many: string): string {
    const n = Math.abs(Math.trunc(count));
    const tail = n % 100;
    if (tail >= 11 && tail <= 14) return many;
    const last = n % 10;
    if (last === 1) return one;
    if (last >= 2 && last <= 4) return few;
    return many;
}

/** «1 день», «22 дня», «11 дней» — самое частое применение правила. */
export function dayWord(days: number): string {
    return plural(days, 'день', 'дня', 'дней');
}
