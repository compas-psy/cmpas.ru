/**
 * Понедельник в будущем — вычисляемый, а не записанный.
 *
 * Раньше в пяти файлах стояло `const MONDAY = '2026-09-07'` с пояснением
 * «настоящий понедельник, достаточно далеко в будущем, чтобы не задеть
 * буфер и горизонт». Седьмое сентября 2026 года наступило, и одиннадцать
 * тестов покраснели разом — не потому, что код сломался, а потому что
 * будущее кончилось.
 *
 * Хуже всего, как это выглядело: утренний прогон был зелёным, дневной
 * красным, диффа между ними нет. На такое уходит час, прежде чем
 * догадаешься посмотреть на календарь.
 *
 * Шестьдесят дней вперёд, потом до ближайшего понедельника: заведомо
 * будущее (буфер записи считается в часах) и заведомо внутри горизонта,
 * который во всех этих проверках равен 365 дням.
 *
 * Имя файла без `.test.` — намеренно: vitest берёт только `*.test.ts`
 * (см. include в vitest.config.mts), иначе файл без единой проверки
 * ронял бы прогон.
 */
export function futureMonday(): string {
    const d = new Date();
    d.setUTCHours(0, 0, 0, 0);
    d.setUTCDate(d.getUTCDate() + 60);
    // 1 — понедельник в нумерации Date.getUTCDay(); dayOfWeek: 0 в наших
    // правилах расписания означает то же самое, это разные нумерации.
    while (d.getUTCDay() !== 1) d.setUTCDate(d.getUTCDate() + 1);
    return d.toISOString().slice(0, 10);
}
