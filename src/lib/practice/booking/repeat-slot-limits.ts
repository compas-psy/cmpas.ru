/**
 * Границы и подсказки повторной записи — ОТДЕЛЬНО ОТ ЯДРА.
 *
 * Числа нужны и серверу, и экрану в браузере. Само ядро (repeat-slot.ts)
 * тянет за собой базу, и импорт его из клиентского компонента утащил бы
 * серверный код в браузерную сборку. Поэтому константы живут здесь, а ядро
 * их переэкспортирует — вызывающие на сервере не заметят разницы.
 */

/**
 * Максимум за один заход — полгода.
 *
 * Было двенадцать недель, и это оказалось не границей здравого смысла, а
 * границей четырёх кнопок в интерфейсе. Учредитель 10.09.2026: «по неделям
 * нужно более гибко, например, 4, 8, 12, предложить своё». «До Нового года»
 * и «до отпуска» в три числа не укладываются, а специалист, которому не дали
 * задать свой срок, заводит остаток встреч руками — ровно то, от чего это
 * действие и избавляет.
 *
 * Полгода — не «сколько угодно»: каждая неделя это настоящая встреча в
 * расписании, и занять год вперёд одним нажатием значит сделать ошибку, на
 * разбор которой уйдёт вечер.
 */
export const MAX_REPEAT_WEEKS = 26;

