/**
 * «Куда человек шёл» — путь, который надо восстановить после входа.
 *
 * Понадобилось из-за бота: он отвечает на пересланный контакт ссылкой
 * https://cmpas.ru/diary/clients?attest=1, а ссылку открывают из
 * мессенджера, где сессии обычно нет. Layout кабинета отправлял такого
 * человека на /auth, ничего не запомнив, а /auth после входа всегда вёл
 * на /diary. Адрес и параметр терялись, окно подтверждения не
 * открывалось — то есть бот снова обещал то, чего не происходило.
 *
 * Значение приходит из адресной строки, то есть от кого угодно. Поэтому
 * разбор строгий: только путь внутри нашего сайта. Без этого параметр
 * «куда вернуться» — классическая открытая переадресация: злоумышленник
 * присылает ссылку на НАШ вход с чужим адресом внутри, человек видит
 * знакомый домен, вводит пароль и оказывается на поддельной странице,
 * уже доверяя ей.
 */

/** Значение по умолчанию: кабинет. Оно же — ответ на любой негодный ввод. */
export const DEFAULT_RETURN_PATH = '/diary';

export function safeReturnPath(raw: string | null | undefined): string {
    if (!raw) return DEFAULT_RETURN_PATH;

    // Один слэш в начале обязателен: так отсекаются и абсолютные адреса
    // (https://зло.example), и протокол-относительные (//зло.example),
    // которые браузер тоже уведёт на чужой домен.
    if (!raw.startsWith('/') || raw.startsWith('//')) return DEFAULT_RETURN_PATH;

    // Обратный слэш браузеры местами трактуют как прямой: /\зло.example
    // уводит наружу так же, как //зло.example.
    if (raw.includes('\\')) return DEFAULT_RETURN_PATH;

    // Пробелы, перевод строки и прочие управляющие символы — способ
    // обмануть разбор адреса и подмешать заголовок в ответ.
    if (/[\u0000-\u0020\u007f]/.test(raw)) return DEFAULT_RETURN_PATH;

    return raw;
}
