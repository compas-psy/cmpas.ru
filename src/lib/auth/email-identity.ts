import { db } from '@/lib/db';

/**
 * ПОЧТА КАК ЛИЧНОСТЬ: ОДИН ЧЕЛОВЕК — ОДНА УЧЁТНАЯ ЗАПИСЬ, НЕЗАВИСИМО ОТ
 * РЕГИСТРА.
 *
 * Сторона СИМПАС просила разобраться с этим четыре раза (issue #132), и
 * просила по делу. У них адрес хранится так, как человек его ввёл, а
 * единственность держится по `lower(email)`. Claim `email` уходит к нам в том
 * виде, в каком человек набрал его у них.
 *
 * У нас же `User.email` — обычный уникальный индекс (prisma/schema.prisma), а
 * Postgres сравнивает строки посимвольно. То есть до этой правки:
 *
 *   практик записан у нас как `Ivan@ya.ru`
 *   → в СИМПАС набирает `ivan@ya.ru`
 *   → поиск по точному совпадению его НЕ находит
 *   → allowDangerousEmailAccountLinking не связывает, а заводит НОВОГО
 *     пользователя ПРАКТИКИ
 *   → человек входит и видит пустую практику вместо своей.
 *
 * Молча. Ни ошибки, ни отказа — узнали бы мы об этом по жалобе «пропали мои
 * клиенты», и не в тот же день.
 *
 * Чинить решено у нас, а не у них. Их вариант — приводить claim к нижнему
 * регистру — закрыл бы только новые входы через СИМПАС и не тронул бы
 * адреса, заведённые у нас раньше и чужими путями (Яндекс, письмо, импорт).
 * Правка у себя защищает и от них тоже.
 *
 * ЗАПИСАННОЕ НЕ ПЕРЕПИСЫВАЕТСЯ. Меняется только сравнение. Адрес человека
 * остаётся в базе таким, каким он его дал: переписать чужие данные ради
 * удобства поиска — не наше право, а обратно уже не восстановить.
 */

/** Приведение к сравнимому виду: убрать края, снять регистр. */
export function normalizeEmail(email: string): string {
    return email.trim().toLowerCase();
}

/**
 * Условие поиска пользователя по почте без учёта регистра.
 *
 * Одно на все места, где ищут человека по адресу. Их три — адаптер
 * next-auth, отправка письма со ссылкой и экран проверки почты, — и до этой
 * правки все три сравнивали ПО-РАЗНОМУ: адаптер точно, письмо точно, а
 * экран приводил к нижнему регистру ВХОД, но не то, что лежит в базе. Три
 * разных ответа на один вопрос «есть ли такой человек».
 */
export function insensitiveEmailWhere(email: string) {
    return { email: { equals: normalizeEmail(email), mode: 'insensitive' as const } };
}

/**
 * Сколько учётных записей отзывается на этот адрес.
 *
 * Обычно одна или ноль. Двойка означает, что расхождение по регистру уже
 * случилось раньше — до этой правки, — и у человека две практики. Такое
 * чинится руками, потому что решать, какая из двух настоящая, код не вправе.
 *
 * В журнал уходит ТОЛЬКО число. Адрес — персональные данные, а журнал читают
 * люди, которым карточек этого человека не показывают.
 */
async function warnOnDuplicates(email: string, found: number): Promise<void> {
    if (found > 1) {
        console.warn(`[auth] на один адрес отзывается учётных записей: ${found} — расхождение по регистру, нужен разбор руками`);
    }
    void email;
}

/**
 * Найти человека по почте без учёта регистра.
 *
 * При нескольких совпадениях берётся САМАЯ СТАРАЯ запись. Это не
 * произвольный выбор: старшая — та, в которой лежит настоящая практика, а
 * младшая появилась как раз из-за расхождения, которое здесь и чинится.
 * Отдавать младшую значило бы показать человеку пустой кабинет — ровно то,
 * от чего эта правка защищает.
 */
export async function findUserByEmailInsensitive(email: string) {
    const matches = await db.user.findMany({
        where: insensitiveEmailWhere(email),
        orderBy: { createdAt: 'asc' },
        take: 2,
    });
    await warnOnDuplicates(email, matches.length);
    return matches[0] ?? null;
}
