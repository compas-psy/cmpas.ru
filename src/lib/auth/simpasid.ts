/**
 * Единый вход СИМПАС (SimpasID, auth.cmpas.ru) — ещё один способ войти
 * рядом с Яндексом и почтой. Ничего не заменяет и не выключает.
 *
 * Здесь только то, что нужно и конфигурации входа, и странице входа, и
 * тестам: настроен ли провайдер и можно ли доверять пришедшей почте.
 * Сам провайдер объявлен в src/auth.ts.
 */

/**
 * Провайдер добавляется, только если заданы все три переменные.
 *
 * Это не перестраховка: next-auth выводит адрес настроек из `issuer`, и
 * провайдер с пустым issuer — это способ входа, который на экране есть, а
 * при нажатии падает. Пока ключ не выдан, кнопки просто нет.
 */
export function isSimpasIdConfigured(): boolean {
    return Boolean(
        process.env.SIMPASID_ISSUER
        && process.env.SIMPASID_CLIENT_ID
        && process.env.SIMPASID_CLIENT_SECRET
    );
}

/** Идентификатор провайдера. Из него же складывается адрес возврата. */
export const SIMPASID_PROVIDER_ID = 'simpasid';

/**
 * Значение ?door, открывающее запасную дверь — экран со входом по почте.
 *
 * Отдельная константа, потому что на неё ссылаются три места: страница
 * входа, экран ошибки и тесты. Строка в трёх местах разошлась бы, и
 * разошлась бы молча — запасная дверь просто перестала бы открываться.
 */
export const EMAIL_DOOR = 'email';

/**
 * ЕДИНЫЙ ВХОД КАК ДВЕРЬ ПО УМОЛЧАНИЮ — СЕЙЧАС ВЫКЛЮЧЕН.
 *
 * Выключено 07.09.2026 по решению учредителя, в день выкладки. Одна строка:
 * поставить true — и дверь снова ведёт в СИМПАС.
 *
 * Почему выключено. Единый вход перестал пускать через Яндекс: СИМПАС
 * отвечает собственной страницей «Вход временно недоступен. Мы уже чиним».
 * Отказ на их стороне — наш сервер и сеть исправны, проба
 * .well-known/openid-configuration отвечала 200 в ту же минуту.
 *
 * Пока это так, дверь по умолчанию ведёт в сломанный вход. Пятнадцать
 * специалистов из шестнадцати через СИМПАС никогда не входили, и первым, что
 * они увидели бы, была бы чужая страница отказа. Заперт при этом никто:
 * запасная дверь работает. Но заставлять каждого искать мелкую ссылку внизу
 * незачем, пока чинят не у нас.
 *
 * ЧТО ДОЛЖНО СТАТЬ ПРАВДОЙ, чтобы вернуть true:
 *   1. сторона СИМПАС подтвердила починку в issue #132;
 *   2. вход через Яндекс проверен на живом человеке.
 *
 * Второй пункт обязателен: проба достижимости издателя отвечала 200 и в
 * момент поломки. Она говорит, что сервис жив, а не что через него можно
 * войти, — и заменять ею проверку значит вернуть дверь вслепую.
 */
export const SIMPASID_IS_DEFAULT_DOOR = false;

/**
 * Показывать ли экран с кнопками — или сразу уводить в СИМПАС.
 *
 * Решение учредителя: единый вход становится дверью по умолчанию. Довод —
 * не экономия клика: Яндекс живёт И внутри СИМПАС, И отдельной кнопкой
 * рядом, то есть на экране было два одинаковых входа с разными
 * последствиями, а слово «СИМПАС» человеку, который пришёл вести практику,
 * ничего не говорит.
 *
 * Запасная дверь остаётся, и это не смягчение решения, а условие его
 * безопасности. Причин две, обе проверены числами на боевом сервере:
 *
 *   1. Пять человек из шестнадцати входят ТОЛЬКО магической ссылкой на
 *      почту — ни одной строки Account. Учётной записи в СИМПАС у них нет,
 *      и без запасной двери правка запирает их снаружи собственной
 *      практики.
 *   2. С редиректом СИМПАС становится единственной точкой отказа для ВСЕХ
 *      входов, включая /admin. Пока дверей две, недоступность auth.cmpas.ru
 *      — неудобство; после — полная потеря доступа к продукту.
 *
 * Дверь не рекламируется: ссылка мелкая и внизу. Задача не в том, чтобы
 * предложить выбор, а в том, чтобы выход существовал.
 */
export function shouldSendToSimpasId(params: {
    configured: boolean;
    door?: string | null;
    /** Только для проверок: боевое значение — константа выше. */
    isDefaultDoor?: boolean;
}): boolean {
    if (!(params.isDefaultDoor ?? SIMPASID_IS_DEFAULT_DOOR)) return false;
    if (!params.configured) return false;
    return params.door !== EMAIL_DOOR;
}

/**
 * КОД ПРОДУКТА ДЛЯ ВОЗВРАТА ИЗ КАБИНЕТА СИМПАС.
 *
 * Не адрес: свободную форму сторона СИМПАС не принимает намеренно — иначе
 * получился бы открытый редирект. Допустимы ровно четыре кода, наш —
 * `practice`.
 */
const SIMPASID_RETURN_CODE = 'practice';

/**
 * Ссылка на личный кабинет СИМПАС.
 *
 * ЗАЧЕМ ОНА ВООБЩЕ. В ПРАКТИКЕ человек управляет тем, что относится к
 * практике. Всё, что относится к нему самому — сведения о себе, способы
 * входа, устройства и сеансы, согласия и рассылки, — живёт не у нас, а на
 * auth.cmpas.ru. Попасть туда из продукта было неоткуда: человеку было
 * негде узнать, что это место вообще есть. На странице профиля при этом
 * стояла подпись «Email обновляется через настройки аккаунта» — то есть мы
 * отсылали в место, дороги к которому не давали.
 *
 * Адрес выводится из issuer, а не пишется строкой: issuer уже задан
 * настройкой, и второй источник правды об одном и том же хосте разошёлся бы
 * молча — на стенде ссылка увела бы в боевой кабинет.
 *
 * `return_to` обязателен: по нему кабинет показывает обратную дорогу
 * «← Вернуться в ПРАКТИКУ». Без него кабинет решит, что человек пришёл сам,
 * набрав адрес руками, и дороги назад не предложит — придумывать её было бы
 * враньём про его путь.
 *
 * Возвращает null, когда единый вход не настроен: ссылка на кабинет, которого
 * у человека нет, — это тупик, а не помощь.
 */
export function simpasIdAccountUrl(section?: 'personal' | 'security' | 'devices' | 'communications' | 'privacy'): string | null {
    const issuer = process.env.SIMPASID_ISSUER;
    if (!issuer) return null;
    const base = issuer.replace(/\/+$/, '');
    const path = section ? `/account/${section}` : '/account';
    return `${base}${path}?return_to=${SIMPASID_RETURN_CODE}`;
}

export function isSimpasIdEmailTrustworthy(profile: unknown): boolean {
    const claims = (profile ?? {}) as { email?: unknown; email_verified?: unknown };
    if (typeof claims.email !== 'string' || claims.email.trim() === '') return false;
    // Строгое сравнение с true, а не «не false»: отсутствующий claim
    // (undefined) — это не подтверждение. Тот же провайдер завтра может
    // перестать его класть, и проверка не должна молча превратиться в
    // проверку `undefined !== false`.
    return claims.email_verified === true;
}

/**
 * Как способ входа называется для человека.
 *
 * Нужно потому, что экран входа показывает это имя в лицо: «Этот email
 * связан с аккаунтом X. Войдите через X». До появления третьего
 * провайдера X всегда был «Яндекс», и подставлять туда идентификатор
 * было негде. С simpasid человек увидел бы в предложении латиницей
 * «simpasid» — строку из нашей конфигурации, которая ему ничего не
 * говорит.
 *
 * nodemailer сюда не попадает: это не «аккаунт», а вход по ссылке.
 */
const PROVIDER_NAMES: Record<string, string> = {
    yandex: 'Яндекс',
    [SIMPASID_PROVIDER_ID]: 'СИМПАС',
};

export function providerDisplayName(providerId: string): string {
    return PROVIDER_NAMES[providerId] ?? providerId;
}

/**
 * Считается ли способ входа «аккаунтом», по которому человека надо
 * отправить обратно вместо входа по почте.
 *
 * Отдельная функция, а не два одинаковых условия: проверка живёт в ДВУХ
 * местах — на экране входа (api/auth/check-email) и в самой отправке
 * письма (auth.ts). Они успели разойтись: экран считал аккаунтом любой
 * провайдер кроме nodemailer, а отправка письма смотрела только на
 * yandex. Пока провайдера было два, разница ничего не значила.
 */
export function isAccountProvider(providerId: string): boolean {
    return providerId !== 'nodemailer';
}
