/**
 * СПИСОК БЛИЖАЙШИХ ВСТРЕЧ В БОТЕ — ОДИН НА ДВА МЕССЕНДЖЕРА.
 *
 * Дефект П2 книги 3. Оба бота отбирали специалисту только подтверждённые
 * встречи — ровно тот фильтр, который у КЛИЕНТА нашли и убрали в тех же
 * двух файлах. У специалиста он тяжелее: у клиента одна встреча, у
 * специалиста день. Клиенты жмут «Подтверждаю» далеко не всегда, и человек
 * с пятью приёмами сегодня слышал от бота, что сессий у него нет.
 *
 * Второе, что чинится здесь же: список молча обрезался пятью записями.
 * Молча — то есть человек не знал, все ли встречи он видит.
 *
 * Почему отдельный модуль на две строки. Правка делается в двух ботах
 * одновременно, и именно так разошлась предыдущая: у клиента поправили, у
 * специалиста забыли. Общее число и общий заголовок расходиться уже не
 * могут — их негде забыть.
 *
 * Модуль намеренно чистый: ни базы, ни отправки. Его зовут оба бота, а они
 * не терпят тяжёлых импортов (за отправкой тянется next-auth).
 */

/**
 * Сколько встреч показывать.
 *
 * Пять — не про экономию, а про чтение: список в мессенджере пролистывают
 * глазами, и всё, что дальше пятой строки, человек всё равно смотрит в
 * кабинете. Число названо, чтобы заголовок ниже мог о нём сказать.
 */
export const SESSIONS_IN_BOT = 5;

/**
 * Заголовок списка, честный насчёт обрезки.
 *
 * Если встреч ровно столько, сколько помещается, — возможно, их больше, и
 * об этом сказано. Меньше — значит показаны все, и оговорка была бы
 * неправдой в другую сторону.
 */
export function sessionsHeading(shown: number): string {
    return shown >= SESSIONS_IN_BOT
        ? `Ближайшие ${SESSIONS_IN_BOT} встреч — остальные в кабинете:`
        : 'Ваши ближайшие встречи:';
}
