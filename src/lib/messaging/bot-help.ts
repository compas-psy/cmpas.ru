import { HELP_TOPICS } from '@/app/diary/help/content';

/**
 * СПРАВКА В БОТЕ — ОДИН ТЕКСТ НА ДВА МЕССЕНДЖЕРА.
 *
 * Дефект П10 книги 3. Справка существовала в трёх видах, и в двух из них её
 * не было: в вебе — восемь тем, написанных живым языком; в MAX — команда
 * `/help` с двумя кнопками; в Telegram — ни команды, ни кнопки. Человек
 * узнавал о возможностях бота, только если угадает слово в меню.
 *
 * Почему общий модуль, а не по команде в каждом боте: справки расходятся
 * ровно так — когда каждая написана по месту. В MAX она успела обзавестись
 * своим списком команд, в Telegram не появилась вовсе.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Восьми тем целиком: в мессенджере их читать нечем, а
 * пересказывать значило бы завести ВТОРУЮ справку, которая разойдётся с
 * первой. Бот называет разделы и ведёт в готовый текст — тот же, что в
 * кабинете.
 *
 * Модуль чистый: списки тем и никакой базы. Его зовут оба бота, а они не
 * терпят тяжёлых импортов — за отправкой тянется next-auth.
 */

export interface BotHelp {
    text: string;
    /** Куда ведёт бот. `path` дописывается к адресу сервиса вызывающим. */
    links: Array<{ label: string; path: string }>;
}

/** Команды, которые бот правда понимает. Расходиться с кодом им нельзя. */
const SPECIALIST_COMMANDS = [
    '/sessions — ближайшие встречи',
    '/link — ссылка для записи клиентов',
    '/help — эта справка',
];

const CLIENT_COMMANDS = [
    '/sessions — ваши ближайшие записи',
    '/help — эта справка',
];

export function botHelpText(forSpecialist: boolean): BotHelp {
    if (!forSpecialist) {
        // Ветка КЛИЕНТА. Ни кабинета, ни справки для специалиста здесь быть
        // не должно: войти туда клиенту нечем, а запись работает по ссылке
        // от его специалиста.
        return {
            text: [
                'Доступные команды:',
                '',
                ...CLIENT_COMMANDS,
                '',
                'Записаться и перенести встречу можно по ссылке, которую присылает ваш специалист.',
            ].join('\n'),
            links: [],
        };
    }

    // Разделы справки называются по тем же именам, что в кабинете: человек
    // должен узнать нужный ещё до перехода.
    const topics = HELP_TOPICS.map((t) => `· ${t.title} — ${t.description}`);

    return {
        text: [
            'Доступные команды:',
            '',
            ...SPECIALIST_COMMANDS,
            '',
            'Справка в кабинете — восемь разделов:',
            '',
            ...topics,
        ].join('\n'),
        links: [
            { label: 'Открыть справку', path: '/diary/help' },
            { label: 'Открыть кабинет', path: '/diary' },
        ],
    };
}
