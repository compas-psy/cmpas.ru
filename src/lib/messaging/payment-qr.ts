import QRCode from 'qrcode';
import { messageLink } from '@/lib/messaging/format';

/**
 * QR оплаты рисуется ИЗ ССЫЛКИ, которую дал специалист.
 *
 * Раньше QR существовал только если специалист отдельно положил адрес
 * картинки (`paymentQrUrl`). То есть заполнив одну ссылку на оплату — а у
 * большинства это статическая ссылка СБП — он получал в сообщении клиенту
 * длинный адрес и никакого кода: клиенту приходилось копировать ссылку
 * руками с телефона, на котором он эту переписку и читает.
 *
 * Код — это та же ссылка, только в виде, который телефон понимает
 * камерой. Поэтому рисуем его сами, а `paymentQrUrl` остаётся ручным
 * переопределением для тех, у кого банк выдал готовую картинку.
 */

/** Ссылка, из которой рисуется код. Пусто — рисовать нечего. */
export function paymentQrSource(settings: {
    paymentLink?: string | null;
    paymentQrUrl?: string | null;
}): string | null {
    // Готовая картинка от банка сильнее: в ней может быть логотип и сумма,
    // которых в голой ссылке нет.
    const explicit = settings.paymentQrUrl?.trim();
    if (explicit) return null; // рисовать не нужно — картинка уже есть
    const link = settings.paymentLink?.trim();
    return link || null;
}

/**
 * PNG с кодом. Размер и поля выбраны так, чтобы код читался с экрана
 * телефона, а не только с печати: мелкий код камера соседнего телефона не
 * берёт, а именно так им и пользуются.
 */
export async function paymentQrPng(link: string): Promise<Buffer> {
    return QRCode.toBuffer(link, {
        type: 'png',
        width: 512,
        margin: 2,
        errorCorrectionLevel: 'M',
        color: { dark: '#1a4d3aff', light: '#ffffffff' },
    });
}

/**
 * ПОДПИСЬ ПОД КОДОМ: ДВА СПОСОБА ЗАПЛАТИТЬ, А НЕ ОДИН.
 *
 * Код уходит отдельной картинкой, а ссылка оплаты — в тексте сообщения
 * выше. Для человека это два разных сообщения, и в том, где код, выбора
 * нет: либо у него под рукой второй телефон с камерой, либо он листает
 * переписку назад искать ссылку.
 *
 * Учредитель 15.09.2026, по живому проходу в MAX: «нужно чтобы у человека
 * был выбор — или отсканировать QR, или перейти по ссылке».
 *
 * Поэтому ссылка едет вместе с кодом и по общему правилу — ЗА СЛОВОМ, а не
 * голым адресом: в Telegram это якорь, в MAX отправка вынимает его в
 * кнопку под картинкой. Подпись собирается в разметке; плоский вид делает
 * сама отправка в MAX, как и для всех остальных сообщений продукта.
 */
export function paymentQrCaption(link?: string | null): string {
    const clean = link?.trim();
    if (!clean) return 'Код для оплаты — наведите камеру телефона';
    // Первая строка про код, вторая — про второй способ. Порядок не
    // случайный: код и есть содержимое картинки, под которой стоит подпись.
    return `Код для оплаты — наведите камеру телефона.\nИли откройте оплату здесь: ${messageLink(clean, 'Перейти к оплате')}`;
}
