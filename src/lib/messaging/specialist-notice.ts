import { db } from '@/lib/db';
import { escapeHtml } from '@/lib/messaging/format';
import { format } from 'date-fns';

/**
 * СПЕЦИАЛИСТУ ПИШУТ В ЕГО КАНАЛ, А НЕ В КАНАЛ КЛИЕНТА.
 *
 * Дефект П3 книги 3 по пути специалиста. Клиент нажимал «Отменить» в
 * Telegram — специалисту уходило сообщение в Telegram. Нажимал в MAX —
 * в MAX. Отменял по ссылке — снова в Telegram. Во всех трёх случаях канал
 * брался не из того, каким мессенджером пользуется САМ специалист, а из
 * того, откуда пришло действие клиента.
 *
 * Значит, специалист, у которого привязан только MAX, не узнавал об отмене,
 * сделанной в Telegram. И наоборот. Правило «писать в тот канал, через
 * который человек пришёл последним» в продукте написано и применяется во
 * всех рассылках — здесь его просто не спрашивали.
 *
 * Полной тишины при этом не было: колокольчик в кабинете получает запись
 * всегда (createNotification рядом с каждым вызовом). Но мессенджер человек
 * привязывал именно затем, чтобы не открывать кабинет ради каждой новости.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ПРАВКА ПО МЕСТУ. Три места сочиняли один и
 * тот же текст трижды, и тексты УЖЕ разошлись: «Клиент X отменил сессию
 * на 17.09 в 13:00», «Клиент X отменил сессию 17.09 в 13:00» и «Отмена
 * сессии… Дата… Время… Слот снова доступен». Правка по месту оставила бы
 * три копии — и следующее расхождение.
 *
 * Имя клиента экранируется здесь и один раз: сообщение уходит с разметкой
 * Telegram, и амперсанд в имени отменил бы его целиком (П5).
 *
 * МОДУЛЬ ЛЁГКИЙ НА ИМПОРТЕ — как reminder-text.ts и payment-instruction.ts.
 * Сама отправка (deliverMessage) тянет за собой Telegram, тот — проверку
 * флага прокси, а та — server action с next-auth: статический импорт этого
 * модуля в бота роняет его тесты с «Cannot find module next/server».
 * Поэтому отправка подтягивается внутри функции, а текст выше остаётся
 * чистым и проверяется вызовом, а не через полдюжины подделок.
 */

/** Что именно сделал клиент. */
export type ClientAction = 'cancelled' | 'confirmed';

export interface ClientActionNotice {
    clientName: string;
    date: Date;
    time: string;
    action: ClientAction;
}

/**
 * Текст сообщения — один на все три пути.
 *
 * Отмена начинается с заголовка, подтверждение — нет: отмена требует
 * действия (час освободился, кого-то можно позвать), подтверждение только
 * снимает вопрос.
 */
export function buildClientActionText(notice: ClientActionNotice): string {
    const who = escapeHtml(notice.clientName);
    const when = `${format(notice.date, 'dd.MM.yyyy')} в ${notice.time}`;

    if (notice.action === 'cancelled') {
        return `<b>Отмена записи</b>\n\nКлиент ${who} отменил встречу ${when}.\nЧас снова свободен.`;
    }
    return `Клиент ${who} подтвердил встречу ${when}.`;
}

/**
 * Сообщить специалисту о действии клиента — в канал специалиста.
 *
 * Читает каналы сам: вызывающие места (два бота и маршрут отмены по ссылке)
 * держат под рукой запись сессии с психологом, но набор выбранных полей у
 * всех трёх разный, и требовать от них одинаковый select — значит завести
 * четвёртое место, где правило можно забыть.
 *
 * Молчит, если писать некуда: колокольчик в кабинете получает запись
 * отдельно и от этой отправки не зависит.
 */
export async function notifySpecialistAboutClientAction(
    psychologistId: string,
    notice: ClientActionNotice,
): Promise<void> {
    try {
        const psy = await db.user.findUnique({
            where: { id: psychologistId },
            select: { telegramChatId: true, maxChatId: true },
        });
        if (!psy) return;
        // ОСНОВНОГО КАНАЛА У СПЕЦИАЛИСТА НЕТ — И МЫ ЕГО НЕ ВЫДУМЫВАЕМ.
        //
        // Поле preferredChannel заведено у КЛИЕНТА (DiaryClient): оно
        // ставится при привязке и означает «через этот канал он пришёл
        // последним». У специалиста такого поля в схеме нет, поэтому здесь
        // работает общий порядок продукта — Telegram, иначе MAX. Главное уже
        // сделано: канал берётся из ЕГО каналов, а не из канала клиента.
        //
        // Подставлять сюда что-то своё значило бы завести второе правило про
        // основной канал; одно такое расхождение продукт уже пережил.
        const { deliverMessage } = await import('@/lib/messaging/deliver');
        await deliverMessage({ ...psy, preferredChannel: null }, buildClientActionText(notice));
    } catch (error) {
        // Не доставили — не повод ронять само действие клиента: встреча уже
        // отменена или подтверждена, и откатывать её из-за мессенджера нельзя.
        console.error('[specialist-notice] не удалось сообщить специалисту:', error);
    }
}
