/**
 * Как название документа показывается ЧЕЛОВЕКУ.
 *
 * Клиент открыл ссылку на согласие и увидел вот что:
 *
 *     Информированное_согласие_оф
 *     Мартынов
 *
 * Заголовок уехал за край экрана и обрезался. Причина не в стилях: название
 * документа — это имя ЗАГРУЖЕННОГО ФАЙЛА, а имя файла у людей выглядит как
 * «Информированное_согласие_оферта___Илья_Мартынов.pdf». Для браузера это
 * одно слово: подчёркивание переносом не является, и перенести такую строку
 * нельзя — только показать целиком или обрезать.
 *
 * Здесь имя файла превращается в название: подчёркивания становятся
 * пробелами, расширение уходит. Это чисто отображение — в базе остаётся то,
 * что записал специалист, и подпись согласия по-прежнему считается от
 * сохранённой версии и хеша, а не от того, что видно на экране.
 *
 * Перенос строки этим НЕ чинится, а только перестаёт быть нужным в частом
 * случае: страница всё равно обязана переносить любую длинную строку сама
 * (break-words), иначе следующее имя без подчёркиваний сломает её снова.
 */

/** Расширения, которые уместно убрать из НАЗВАНИЯ. Файл остаётся файлом. */
const FILE_EXTENSION = /\.(pdf|docx?|rtf|odt|txt|jpe?g|png|heic)$/i;

export function documentDisplayTitle(title: string | null | undefined, fileName?: string | null): string {
    const raw = (title ?? '').trim() || (fileName ?? '').trim();
    if (!raw) return 'Документ';

    const humanized = raw
        .replace(FILE_EXTENSION, '')
        // Ряд подчёркиваний — это след пробелов и разделителей в имени файла.
        // Схлопываем в один пробел: «оферта___Илья» это «оферта Илья», а не
        // «оферта   Илья».
        .replace(/_+/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();

    // Пустой результат означает, что название состояло из одних подчёркиваний
    // или расширения. Тогда честнее показать исходное, чем пустоту.
    return humanized || raw;
}
